import { build, emptyDir } from "@deno/dnt";

const denoPkg = JSON.parse(await Deno.readTextFile("./deno.json"));

// The npm package name to build (e.g., "@webpqc/hqc").
const pkgName = Deno.args[0];
// The output directory name under npm/ (e.g., "webpqc-hqc").
const dirName = pkgName.replace(/^@/, "").replace("/", "-");
const isScoped = pkgName.startsWith("@");

// pre build steps
await emptyDir(`../../npm/${dirName}`);

await build({
  entryPoints: ["./mod.ts"],
  outDir: "../../npm/" + dirName,
  typeCheck: "both",
  test: true,
  declaration: "inline",
  scriptModule: false,
  importMap: "../../npm/import_map.json",
  compilerOptions: {
    lib: ["ES2022", "DOM"],
  },
  shims: {
    deno: "dev",
  },
  testPattern: "test/**/*.test.ts",
  package: {
    name: pkgName,
    version: denoPkg.version,
    description:
      "An HQC (Hamming Quasi-Cyclic) implementation written in TypeScript for various JavaScript runtimes",
    repository: {
      type: "git",
      url: "git+https://github.com/dajiaji/crystals-kyber-js.git",
    },
    homepage:
      "https://github.com/dajiaji/crystals-kyber-js/tree/main/packages/hqc#readme",
    license: "MIT",
    main: "./esm/mod.js",
    module: "./esm/mod.js",
    types: "./esm/mod.d.ts",
    sideEffects: false,
    exports: {
      ".": {
        "types": "./esm/mod.d.ts",
        "default": "./esm/mod.js",
      },
      "./package.json": "./package.json",
    },
    keywords: [
      "hqc",
      "hqc-kem",
      "hamming-quasi-cyclic",
      "kem",
      "security",
      "encryption",
      "pqc",
      "post-quantum",
    ],
    engines: {
      "node": ">=20.0.0",
    },
    author: "Ajitomi Daisuke",
    bugs: {
      url: "https://github.com/dajiaji/crystals-kyber-js/issues",
    },
    // Scoped packages are private by default.
    ...(isScoped ? { publishConfig: { access: "public" } } : {}),
  },
});

// post build steps
Deno.copyFileSync("LICENSE", `../../npm/${dirName}/LICENSE`);
Deno.copyFileSync("README.md", `../../npm/${dirName}/README.md`);

const outDir = `../../npm/${dirName}`;

// Mark the package as ESM at the top level. This has to be done after the
// build because the test runner generated by dnt is a CommonJS script.
const pkgPath = `${outDir}/package.json`;
const pkg = JSON.parse(await Deno.readTextFile(pkgPath));
const esmPkg = Object.fromEntries(
  Object.entries(pkg).flatMap(([k, v]) =>
    k === "main" ? [["type", "module"], [k, v]] : [[k, v]]
  ),
);
await Deno.writeTextFile(pkgPath, JSON.stringify(esmPkg, null, 2) + "\n");

// Remove test-only files from the npm package
for (const dir of ["esm"]) {
  await emptyDir(`${outDir}/${dir}/deps`);
  await Deno.remove(`${outDir}/${dir}/deps`, { recursive: true });
  await emptyDir(`${outDir}/${dir}/test`);
  await Deno.remove(`${outDir}/${dir}/test`, { recursive: true });
  try {
    await Deno.remove(`${outDir}/${dir}/_dnt.test_shims.d.ts`);
  } catch { /* ignore */ }
  try {
    await Deno.remove(`${outDir}/${dir}/_dnt.test_shims.d.ts.map`);
  } catch { /* ignore */ }
  try {
    await Deno.remove(`${outDir}/${dir}/_dnt.test_shims.js`);
  } catch { /* ignore */ }
}
